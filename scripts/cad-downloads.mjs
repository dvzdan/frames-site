import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = path.join(repoRoot, "cad", "release-manifest.json");
const mappings = [
  {
    name: "dry wall rig.scad",
    source: "cad/source/dry wall rig.scad",
    public: "assets/downloads/dry wall rig.scad",
  },
  {
    name: "latch and keeper.scad",
    source: "cad/source/latch and keeper.scad",
    public: "assets/downloads/latch and keeper.scad",
  },
];

function absolute(relativePath) {
  return path.join(repoRoot, ...relativePath.split("/"));
}

function sha256(buffer) {
  return createHash("sha256").update(buffer).digest("hex");
}

async function sourceEntries() {
  return Promise.all(
    mappings.map(async (mapping) => ({
      ...mapping,
      sha256: sha256(await readFile(absolute(mapping.source))),
    })),
  );
}

async function sync() {
  const entries = await sourceEntries();
  for (const entry of entries) {
    await mkdir(path.dirname(absolute(entry.public)), { recursive: true });
    await copyFile(absolute(entry.source), absolute(entry.public));
  }

  const manifest = {
    schemaVersion: 1,
    note: "Generated by npm run cad:sync. Edit cad/source, not assets/downloads.",
    files: entries,
  };
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  console.log(`Synchronized ${entries.length} CAD download files.`);
}

async function check() {
  const expected = await sourceEntries();
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  const problems = [];

  if (manifest.schemaVersion !== 1) problems.push("manifest schemaVersion is not 1");
  if (JSON.stringify(manifest.files) !== JSON.stringify(expected)) {
    problems.push("release manifest does not match the canonical CAD sources");
  }

  for (const entry of expected) {
    const publicHash = sha256(await readFile(absolute(entry.public)));
    if (publicHash !== entry.sha256) {
      problems.push(`${entry.public} differs from ${entry.source}`);
    }
  }

  if (problems.length) {
    console.error("CAD release check failed:");
    for (const problem of problems) console.error(`- ${problem}`);
    console.error("Run npm run cad:sync, then check the resulting changes.");
    process.exitCode = 1;
    return;
  }
  console.log(`Verified ${expected.length} canonical CAD download files.`);
}

const command = process.argv[2];
if (command === "sync") await sync();
else if (command === "check") await check();
else {
  console.error("Usage: node scripts/cad-downloads.mjs <sync|check>");
  process.exitCode = 2;
}
